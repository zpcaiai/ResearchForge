def test_a_fabricated_claim_fails_evidence_support(tmp_path):
    project = build_project(tmp_path / "p")
    audit = [json.loads(l) for l in
             (project / "review/claim_audit.jsonl").read_text().splitlines() if l.strip()]
    audit.append({
        "claim_id": "C-002", "locator": "Results#p1", "section": "Results",
        "text": "Throughput improved by 41.7%.", "quantitative": True,
        "citations": [], "resolved_citations": [], "unresolved_citations": [],
        "supporting_edges": [], "number_checks": [{"value": "41.7", "matched": False,
                                                   "ledger_entry": None}],
        "verdict": "FABRICATED",
        "reason": "the number matches no recorded metric", "remediation": "delete it"})
    _w(project, "review/claim_audit.jsonl", audit)
    gate = json.loads((project / "review/integrity_gate.json").read_text())
    gate["counts"]["FABRICATED"] = 1
    gate["verdict"] = "BLOCK"
    _w(project, "review/integrity_gate.json", gate)

    result = run_grade(project, project)
    assert outcomes(result)["evidence_support"] == "FAIL"
    assert result["verdict"] == "REJECTED"
    assert check(result, "evidence_support", "E4.1_zero_fabricated")["outcome"] == "FAIL"
    # The untraced number is reported too — the same defect seen from the other side.
    assert check(result, "evidence_support",
                 "E4.3_quantitative_claims_traced")["outcome"] == "FAIL"


