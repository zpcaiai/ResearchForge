def run_grade(project: Path, second: Path | None = None):
    return grade_mod.grade(project, REPO, second)


def outcomes(result):
    return {d["id"]: d["outcome"] for d in result["dimensions"]}


def check(result, dim_id, check_id):
    for d in result["dimensions"]:
        if d["id"] == dim_id:
            for c in d["checks"]:
                if c["id"] == check_id:
                    return c
    raise AssertionError(f"{dim_id}/{check_id} not in the report")


