def test_an_ablation_measured_on_its_own_metric_fails(tmp_path):
    """The shape a retried null takes, and a contrast nobody can compute either way."""
    project = build_project(tmp_path / "p")
    specs = json.loads((project / "experiments/E-ABL-001.yaml").read_text())
    specs[0]["metrics"] = [{"name": "mechanism_activation", "role": "decision"}]
    _w(project, "experiments/E-ABL-001.yaml", specs)
    ledger = [json.loads(l) for l in
              (project / "experiment_ledger.jsonl").read_text().splitlines() if l.strip()]
    for e in ledger:
        if e["experiment_id"] == "E-ABL-001":
            e["metrics"] = {"mechanism_activation": e["metrics"]["primary"]}
            e["provenance"]["declared_metrics"] = ["mechanism_activation"]
    _w(project, "experiment_ledger.jsonl", ledger)

    result = run_grade(project, project)
    c = check(result, "ablations",
              "E3.3a_ablation_shares_a_metric_with_its_primary_experiment")
    assert c["outcome"] == "FAIL"
    assert outcomes(result)["ablations"] == "FAIL"


