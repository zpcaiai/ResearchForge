    result = run_grade(project, project)
    ratio = check(result, "evidence_support", "E4.2_support_ratio")
    assert ratio["outcome"] == "FAIL"
    assert ratio["measured"] == 0.2 and ratio["threshold"] == 0.95
    assert check(result, "evidence_support", "E4.1_zero_fabricated")["outcome"] == "PASS"


