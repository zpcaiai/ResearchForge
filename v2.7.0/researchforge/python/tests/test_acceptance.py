def test_a_project_that_satisfies_every_dimension_is_accepted(tmp_path):
    project = build_project(tmp_path / "p")
    second = tmp_path / "p-second"
    # Same inputs, same outputs: this is what the determinism dimension asks for,
    # and it must be supplied rather than assumed.
    shutil.copytree(project, second)

    result = run_grade(project, second)
    assert result["verdict"] == "ACCEPTED", (
        f"{result['verdict_reason']}\n"
        + json.dumps([c for d in result["dimensions"] for c in d["checks"]
                      if c["outcome"] not in ("PASS", "NOT_APPLICABLE")], indent=1))
    assert result["failed_dimensions"] == []
    assert result["not_measured_dimensions"] == []
    assert len(result["dimensions"]) == 8
    assert all(o in ("PASS", "NOT_APPLICABLE") for o in outcomes(result).values())


def test_without_a_second_run_reproducibility_is_not_measured_and_blocks_acceptance(tmp_path):
    project = build_project(tmp_path / "p")
    result = run_grade(project)
    assert outcomes(result)["reproducibility"] == "NOT_MEASURED"
    # The distinction the whole grader turns on: nothing failed, and it is still
    # not accepted.
    assert result["failed_dimensions"] == []
    assert result["verdict"] == "INCOMPLETE"


