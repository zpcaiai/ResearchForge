def _spec_doc(experiment_id, claim_type, baseline, *, ablation_ref=None):
    """An ExperimentSpec of the shape research-blueprint-compiler emits.

    Carries one machine-evaluable invalid_condition alongside the prose ones,
    because rf_runtime returns a prose condition as *unchecked* and the rubric
    grades on what the run could actually enforce.
    """
    doc = {
        "experiment_id": experiment_id,
        "claim_type": claim_type,
        "hypothesis": "the mechanism raises the primary metric",
        "baseline": baseline,
        "candidate": {"description": "the method under test"},
        "datasets": [{"name": "fixture", "resolved": True}],
        "metrics": [{"name": "primary", "role": "decision"}],
        "seeds": [1, 2, 3],
        "resources": {"seeds": 3, "conditions": 2, "runs": 6},
        "invalid_conditions": [
            {"code": "PRIMARY_DEGENERATE", "metric": "primary", "op": "<=", "value": 0.0,
             "why": "a non-positive primary metric means the evaluator did not score the run"},
            {"code": "EVALUATOR_CHANGED_MID_RUN",
             "condition": "the evaluator digest differs between the first and last run",
             "why": "conditions scored by different evaluators are not comparable"},
        ],
    }
    if ablation_ref:
        doc["ablation_ref"] = ablation_ref
    return doc


def _ledger_entry(experiment_id, seed, value, entry_point):
    return {
        "run_id": "run-acceptance", "experiment_id": experiment_id,
        "attempt_id": f"{experiment_id}:seed={seed}", "seed": seed,
        "status": "COMPLETED", "metrics": {"primary": value},
        "artifacts": [{"path": entry_point, "role": "entry_point"}], "warnings": [],
        "provenance": {"skill": "experiment-runner", "entry_point": entry_point,
                       "declared_metrics": ["primary"], "executed": True,
                       "evaluator_version": "ev-1", "environment_digest": "env-1"},
    }


