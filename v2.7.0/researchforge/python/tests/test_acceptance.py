"""What the acceptance grader refuses to accept.

The grader's happy path is trivial — it emits a report either way. What is worth
testing is the set of things it must not do: pass a project with a fabricated
claim, pass a figure that argues for nothing, pass a dimension it could not see,
and put a score on offline-stub output at all.

Every fixture here is built in tmp_path from literals rather than by running the
pipeline, because a fixture produced by the system under test cannot demonstrate
that the grader would have caught the system being wrong.
"""
import importlib.util
import json
import shutil
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
GRADE_PY = REPO / "acceptance" / "grade.py"

# The grader is an operator script, not a package: it must run against a project
# directory on a machine where `researchforge` may not be installed at all. So it
# is loaded by path here rather than imported, and registered in sys.modules
# before execution because @dataclass resolves annotations through it.
_spec = importlib.util.spec_from_file_location("rf_acceptance_grade", GRADE_PY)
grade_mod = importlib.util.module_from_spec(_spec)
sys.modules["rf_acceptance_grade"] = grade_mod
_spec.loader.exec_module(grade_mod)


# --------------------------------------------------------------------------
# fixture builder
# --------------------------------------------------------------------------
def _w(root: Path, rel: str, payload) -> Path:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(payload, str):
        p.write_text(payload, encoding="utf-8")
    elif rel.endswith(".jsonl"):
        p.write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in payload),
                     encoding="utf-8")
    else:
        p.write_text(json.dumps(payload, indent=1, sort_keys=True), encoding="utf-8")
    return p


#: The generated runner's shape, reduced to the two tokens the grader looks for.
#: The real one is produced by codebase-scaffolder from _EXPERIMENT_MODULE.
ENTRY_POINT_SRC = '''"""GENERATED by researchforge codebase-scaffolder."""
from rf_runtime import check_invalid_conditions, emit, seed_everything

SPEC = {"experiment_id": "%s"}
INVALID_CONDITIONS = SPEC.get("invalid_conditions") or []


def main(metrics):
    fired, unchecked = check_invalid_conditions(INVALID_CONDITIONS, metrics)
    emit({"status": "INVALID" if fired else "COMPLETED", "metrics": metrics})
'''

